"""Controlled labelled test of the guide assessment, on held-out sales.

Why this exists alongside hardcases.py. hardcases.py scores REAL listings
labelled by a person, which is the ideal test, and that set has not been
collected. This is the test we can run honestly now: the correct answer is
known by construction, because the eventual sale price is known.

    For 40 sales from the frozen test set (contracts from 2025-10-01, never seen
    by the model or the comparable-sales index), score four guides:
        100% of the actual sale price  -> label "defensible"   (must stay quiet)
         90%                           -> label "borderline"   (reported, not scored)
         80%, 70%                      -> label "underquoted"  (should be flagged)

    "Flagged" means the tool's own band: "below" or "well below" the evidence
    (severity notable or strong).

What it cannot tell you. A guide at 80% of the eventual price is a large gap,
but in a hot auction a real agent could still have set it honestly. The labels
measure whether the tool detects a known gap to the true price, not whether an
agent broke the law. That still needs hardcases.py and real listings.

    python src/controlled_cases.py           build the case file if missing, then score it
    python src/controlled_cases.py --rebuild draw a fresh sample (changes the test set)

Writes data/reference/controlled_cases.csv (the inputs, usable with
check.py --csv), results/controlled_cases_results.csv (every case) and
results/controlled_cases.md (the summary).
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

import config as C
import serve

ROOT = Path(__file__).resolve().parents[1]
CASES = C.REF / "controlled_cases.csv"
OUT_CSV = ROOT / "results" / "controlled_cases_results.csv"
OUT_MD = ROOT / "results" / "controlled_cases.md"
SEED, PER_STRATUM = 20261006, 10
LEVELS = {1.00: "defensible", 0.90: "borderline", 0.80: "underquoted", 0.70: "underquoted"}
FLAG = {"notable", "strong"}


def build():
    df = pd.read_parquet(C.ROOT / "data" / "processed" / "sales_features.parquet",
                         columns=["address", "suburb", "postcode", "property_type", "land_area_m2",
                                  "contract_date", "sale_price", "dist_cbd_km"])
    test = df[df["contract_date"] >= C.CALIB_END].copy()
    test["segment"] = np.where(test["dist_cbd_km"] < 50, "metro", "regional")
    picks = test.groupby(["segment", "property_type"]).sample(n=PER_STRATUM, random_state=SEED)
    rows = []
    for i, s in enumerate(picks.itertuples(), 1):
        for ratio, label in LEVELS.items():
            rows.append({"case_id": f"C{i:02d}-{int(ratio * 100)}", "suburb": s.suburb,
                         "postcode": str(s.postcode).zfill(4), "property_type": s.property_type,
                         "land_area_m2": "" if pd.isna(s.land_area_m2) else round(s.land_area_m2),
                         "guide": int(round(s.sale_price * ratio, -3)), "label": label,
                         "guide_pct_of_sale": int(ratio * 100), "sale_price": int(s.sale_price),
                         "contract_date": str(s.contract_date)[:10], "segment": s.segment,
                         "address": s.address})
    out = pd.DataFrame(rows)
    out.to_csv(CASES, index=False)
    print(f"wrote {len(out)} cases ({len(picks)} properties) to {CASES}")


def rate(mask):
    return f"{mask.mean() * 100:.0f}% ({int(mask.sum())}/{len(mask)})"


def score():
    cases = pd.read_csv(CASES, dtype={"postcode": str})
    rows = []
    for c in cases.itertuples():
        r = serve.value_manual(suburb=c.suburb, postcode=c.postcode, property_type=c.property_type,
                               land_area_m2=None if pd.isna(c.land_area_m2) else c.land_area_m2,
                               guide=c.guide, when=c.contract_date)
        rows.append({**c._asdict(), "severity": r.get("severity"), "band": r.get("band"),
                     "comps_percentile": r.get("comps_percentile"),
                     "gap_in_typical_errors": r.get("gap_in_typical_errors"),
                     "comps_estimate": r.get("comps_estimate"), "comps_n": r.get("comps_n")})
    out = pd.DataFrame(rows).drop(columns="Index")
    out["flagged"] = out["severity"].isin(FLAG)
    out["comps_vs_sale_pct"] = (out["comps_estimate"] / out["sale_price"] - 1) * 100
    out.to_csv(OUT_CSV, index=False)

    pos, neg = out[out["label"] == "underquoted"], out[out["label"] == "defensible"]
    tp, fp = pos["flagged"].sum(), neg["flagged"].sum()
    precision = tp / (tp + fp) if tp + fp else float("nan")
    md = [f"# Controlled labelled test of the guide assessment\n",
          f"{out['case_id'].str[:3].nunique()} held-out sales x 4 guide levels = {len(out)} cases. "
          f"Flagged = band \"below\" or \"well below\". Generated by src/controlled_cases.py.\n",
          "## At the tool's own threshold\n",
          "| | Result |", "|---|---|",
          f"| Underquoted guides flagged (recall) | {rate(pos['flagged'])} |",
          f"| Defensible guides wrongly flagged (false-positive rate) | {rate(neg['flagged'])} |",
          f"| Precision (flags that were real gaps) | {precision * 100:.0f}% ({tp}/{tp + fp}) |\n",
          "## By guide level\n", "| Guide as % of actual sale | Label | Flagged | Any warning (incl. \"low end\") |",
          "|---|---|---|---|"]
    for pct, g in out.groupby("guide_pct_of_sale", sort=False):
        md.append(f"| {pct}% | {g['label'].iloc[0]} | {rate(g['flagged'])} | "
                  f"{rate(g['severity'].isin(FLAG | {'mild'}))} |")
    md += ["\n## By segment and type (recall on underquoted / false positives on defensible)\n",
           "| Segment | Type | Recall | False positives |", "|---|---|---|---|"]
    for (seg, typ), g in out.groupby(["segment", "property_type"]):
        md.append(f"| {seg} | {typ} | {rate(g.loc[g['label'] == 'underquoted', 'flagged'])} | "
                  f"{rate(g.loc[g['label'] == 'defensible', 'flagged'])} |")
    md += ["\n## Threshold sweep (gap in typical errors)\n",
           "| Flag when gap >= | Recall | False positives |", "|---|---|---|"]
    for cut in (0.5, 0.75, 1.0, 1.5, 2.0):
        md.append(f"| {cut:.2f}x{' (shipped)' if cut == 1.0 else ''} | "
                  f"{rate(pos['gap_in_typical_errors'] >= cut)} | {rate(neg['gap_in_typical_errors'] >= cut)} |")
    md += ["\n## Where the comparables were wrong\n",
           f"Median comparable-sales estimate vs actual sale: {out['comps_vs_sale_pct'].median():+.1f}%. "
           "Every miss and every false positive traces to the comparable estimate sitting far from the "
           "price the property actually sold for:\n",
           "| Case | Suburb | Type | Sold | Comparable estimate | Off by | Guide | Result |", "|---|---|---|---|---|---|---|---|"]
    bad = pd.concat([neg[neg["flagged"]], pos[~pos["flagged"]]])
    for c in bad.sort_values("comps_vs_sale_pct").itertuples():
        md.append(f"| {c.case_id} | {c.suburb} | {c.property_type} | ${c.sale_price:,.0f} | "
                  f"${c.comps_estimate:,.0f} | {c.comps_vs_sale_pct:+.0f}% | {c.guide_pct_of_sale}% "
                  f"| {'false positive' if c.label == 'defensible' else 'missed'} ({c.severity}) |")
    md.append("\nLabels are known by construction from the eventual sale price. They test whether the tool "
              "detects a known gap, not whether an agent broke the law; see the module docstring.")
    OUT_MD.write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md[:14]))
    print(f"\nwrote {OUT_CSV} and {OUT_MD}")


if __name__ == "__main__":
    if "--rebuild" in sys.argv or not CASES.exists():
        build()
    score()
